"use strict";
const map = <A, B>(list: A[], f: (a: A) => B): B[] => list.map(f);
const filter = <A>(list: A[], pred: (a: A) => boolean): A[] => list.filter(pred);
const length = <A>(list: A[]): number => list.length;
const joinWith = (list: string[], sep: string): string => list.join(sep);
const any = <A>(list: A[], pred: (a: A) => boolean): boolean => list.some(pred);
const split = (s: string, sep: string): string[] => s.split(sep);
const trim = (s: string): string => s.trim();
const toUpper = (s: string): string => s.toUpperCase();
const toLower = (s: string): string => s.toLowerCase();
const wordCount = (text) => length(filter(split(trim(text), " "), (w): boolean => w !== ""));
const capitalize = (words) => joinWith(map(words, toUpper), " ");
const csvRow = (fields) => joinWith(fields, ",");
const hasKeyword = (text, keyword) => any(split(toLower(text), " "), (w): boolean => w === toLower(keyword));
