"use strict";
const map = (list, f) => list.map(f);
const filter = (list, pred) => list.filter(pred);
const length = list => list.length;
const joinWith = (list, sep) => list.join(sep);
const any = (list, pred) => list.some(pred);
const split = (s, sep) => s.split(sep);
const trim = s => s.trim();
const toUpper = s => s.toUpperCase();
const toLower = s => s.toLowerCase();
const wordCount = text => length(filter(split(trim(text), " "), w => w !== ""));
const capitalize = words => joinWith(map(words, toUpper), " ");
const csvRow = fields => joinWith(fields, ",");
const hasKeyword = (text, keyword) => any(split(toLower(text), " "), w => w === toLower(keyword));
