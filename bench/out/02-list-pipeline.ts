"use strict";
const map = <A, B>(list: A[], f: (a: A) => B): B[] => list.map(f);
const filter = <A>(list: A[], pred: (a: A) => boolean): A[] => list.filter(pred);
const fold = <A, B>(list: A[], init: B, f: (acc: B, x: A) => B): B => list.reduce(f, init);
const length = <A>(list: A[]): number => list.length;
const range = (start: number, end: number): number[] => Array.from(Array(end - start), (_, i) => start + i);
const reverse = <A>(list: A[]): A[] => [...list].reverse();
const slice = <A>(list: A[], from: number, to: number): A[] => list.slice(from, to);
const startsWith = (s: string, prefix: string): boolean => s.startsWith(prefix);
const sort = (list: number[]): number[] => [...list].sort((a, b) => a - b);
const sumEvenSquares = (n) => fold(map(filter(range(1, n + 1), (x): boolean => (x % 2) === 0), (x) => x * x), 0, (_a, _b) => _a + _b);
const topN = (ns, n) => slice(reverse(sort(ns)), 0, n);
const tagList = (tags, prefix) => length(filter(tags, (t): boolean => startsWith(t, prefix)));
